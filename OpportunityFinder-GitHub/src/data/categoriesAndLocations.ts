/**
 * Helper to get country configuration
 */
export function getCountryLocation(countryName: string): CountryLocation | undefined {
  const normalized = countryName.trim().toLowerCase();
  return PREDEFINED_COUNTRIES_DATA.find(
    (c) =>
      c.country.toLowerCase() === normalized ||
      (normalized === 'uk' && c.country === 'United Kingdom') ||
      (normalized === 'usa' && c.country === 'United States') ||
      (normalized === 'us' && c.country === 'United States') ||
      (normalized === 'uae' && c.country === 'United Arab Emirates') ||
      (normalized === 'deutschland' && c.country === 'Germany') ||
      (normalized === 'österreich' && c.country === 'Austria') ||
      (normalized === 'schweiz' && c.country === 'Switzerland')
  );
}

/**
 * Helper to get cities for a given country name
 */
export function getCitiesForCountry(countryName: string): string[] {
  const found = getCountryLocation(countryName);
  return found ? found.cities : [];
}

/**
 * Helper to get default city for a country
 */
export function getDefaultCityForCountry(countryName: string): string {
  const found = getCountryLocation(countryName);
  return found ? found.defaultCity : 'Frankfurt am Main';
}

/**
 * Helper to get popular cities for a country
 */
export function getPopularCitiesForCountry(countryName: string): string[] {
  const found = getCountryLocation(countryName);
  return found ? found.popularCities : [];
}
